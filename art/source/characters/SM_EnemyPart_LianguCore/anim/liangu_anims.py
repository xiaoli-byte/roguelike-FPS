"""连鼓灵（SM_EnemyPart_LianguCore + 6 × LianguDrum + LianguMallet）骨槌击鼓的手工关键帧（第四章移植 E 路）。

连鼓灵是静态部件组装的、没有骨架，不走原生采样，也没有 Animator：动作就是三样东西的变换——
  骨槌 MalletPivot：绕水平轴的摆角 swing（度；0 = 竖直朝上，90 = 水平朝外，120 ≈ 砸到鼓面）+ 握点上下 pivotDip（米）
  鼓环 Ring：被砸得往下一沉 ringDip（米）
  被敲的那面鼓：鼓面一鼓 facePop（缩放增量）
这里按设计单 docs/art/vfx/foes-ch4.md 6.1 的节拍表手 K 这四条曲线（一拍 1.2 s = 36 帧），生成 Unity 用的
unity/Assets/Game/Scripts/Enemies/AI/Plateau/LianguKeys.cs（AnimationCurve 关键帧 + 切线，别手改，改这里再跑一次）：

    python art/source/characters/SM_EnemyPart_LianguCore/anim/liangu_anims.py [--out <路径>]

节拍（帧 @30 fps）：
  0  起手 key：骨槌在静止角 69°（斜上朝外）
  4  反向预备：往回抬到 49°，握点微抬 0.05 m（举锤）
  7  breakdown：下砸过半 90°（smear 段，越来越快）
  7.5 释放帧（= 0.25 s，事件 beat）：120° 砸在鼓面上，握点压低 0.12 m；鼓环下沉 0.08 m、鼓面鼓起 10%
  9  弹起 108°（过冲回弹）
  10 再落 116°（overlapping：锤头二次颤）
  16 收回 85°；鼓环回弹 +0.02 m
  36 回到静止 69°
切线：释放帧之前「越来越快」（入切线 = 前一段斜率的 1.6 倍、出切线 0 = 砸住），其余按相邻斜率的平均（Catmull-Rom），首尾为 0。
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
OUT = ROOT / "unity/Assets/Game/Scripts/Enemies/AI/Plateau/LianguKeys.cs"
FPS = 30.0
LENGTH = 1.2
PIVOT_HEIGHT = 0.75
STRIKE = 7.5  # 释放帧（帧）

# (帧, 值)；STRIKE 帧是「砸住」的键
SWING = [(0, 69), (4, 49), (7, 90), (STRIKE, 120), (9, 108), (10, 116), (16, 85), (36, 69)]
PIVOT_DIP = [(0, 0.0), (4, 0.05), (STRIKE, -0.12), (11, 0.0), (36, 0.0)]
RING_DIP = [(0, 0.0), (7.2, 0.0), (STRIKE, -0.08), (10.8, 0.02), (15, 0.0), (36, 0.0)]
FACE_POP = [(0, 0.0), (7.2, 0.0), (STRIKE, 0.10), (12, 0.0), (36, 0.0)]


def tangents(keys):
    """每个键的 (入, 出) 切线（值 / 秒）"""
    out = []
    n = len(keys)
    for i, (f, v) in enumerate(keys):
        t = f / FPS
        if i == 0 or i == n - 1:
            out.append((0.0, 0.0))
            continue
        tp, vp = keys[i - 1][0] / FPS, keys[i - 1][1]
        tn, vn = keys[i + 1][0] / FPS, keys[i + 1][1]
        sp = (v - vp) / max(1e-4, t - tp)
        sn = (vn - v) / max(1e-4, tn - t)
        if abs(f - STRIKE) < 1e-3:
            out.append((sp * 1.6, 0.0))  # 砸住：冲进来、停在鼓面上
        else:
            m = 0.5 * (sp + sn)
            # 极值点（前后斜率异号）切线为 0，不冲过头
            out.append((0.0, 0.0) if sp * sn < 0 else (m, m))
    return out


def curve(name, keys, doc):
    tan = tangents(keys)
    rows = ",\n".join(f"            new Keyframe({f / FPS:.4f}f, {v:.4f}f, {a:.4f}f, {b:.4f}f)" for (f, v), (a, b) in zip(keys, tan))
    return f"""        /// <summary>{doc}</summary>
        public static readonly AnimationCurve {name} = new(
{rows});
"""


def main():
    argv = sys.argv[1:]
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else OUT
    body = "\n".join([
        curve("Swing", SWING, "骨槌摆角（度；0 = 竖直朝上、90 = 水平朝外、120 ≈ 砸在鼓面上）"),
        curve("PivotDip", PIVOT_DIP, "握点上下（米）"),
        curve("RingDip", RING_DIP, "鼓环下沉（米）"),
        curve("FacePop", FACE_POP, "被敲那面鼓的缩放增量"),
    ])
    src = f"""// <auto-generated>由 art/source/characters/SM_EnemyPart_LianguCore/anim/liangu_anims.py 生成，别手改。</auto-generated>
using UnityEngine;

namespace Spiritfire.Game
{{
    /// <summary>
    /// 连鼓灵骨槌击鼓的手工关键帧（设计单 docs/art/vfx/foes-ch4.md 6.1）：一拍 {LENGTH} s，释放帧 {STRIKE / FPS:.3f} s（= 招式 beat 的 beat 事件）。
    /// 连鼓灵是静态部件组装、没有 Animator，<see cref="LianguAI"/> 每帧按这几条曲线摆骨槌、鼓环和鼓面。
    /// </summary>
    public static class LianguKeys
    {{
        public const float Length = {LENGTH}f, Strike = {STRIKE / FPS:.4f}f, PivotHeight = {PIVOT_HEIGHT}f;

{body}    }}
}}
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src, encoding="utf-8")
    print("LIANGU_KEYS", out)


main()
