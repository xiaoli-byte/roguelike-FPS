# 草甸是一整片能走的地（不是只有路）：村北林线、啸獭洞在草甸里
MEADOW = [(-230, -120), (-150, -150), (-40, -120), (20, -40), (10, 60), (-10, 200), (-230, 200)]


def in_poly(x, z, poly):
    c = False
    for (x1, z1), (x2, z2) in zip(poly, poly[1:] + poly[:1]):
        if (z1 > z) != (z2 > z) and x < (x2 - x1) * (z - z1) / (z2 - z1) + x1:
            c = not c
    return c


def seg_dist(px, pz, a, b):
    ax, az, bx, bz = a[0], a[1], b[0], b[1]
    dx, dz = bx - ax, bz - az
    t = max(0.0, min(1.0, ((px - ax) * dx + (pz - az) * dz) / (dx * dx + dz * dz or 1)))
    return math.hypot(px - ax - t * dx, pz - az - t * dz)


def main():
    bad = 0
    print("| 路 | 段数 | 水平长 | 升高 | 最陡一段 | 上限 | 结果 |")
    print("|---|---|---|---|---|---|---|")
    for name, lim, pts in ROUTES:
        L = rise = 0.0
        worst = 0.0
        for a, b in zip(pts, pts[1:]):
            h = math.hypot(b[0] - a[0], b[1] - a[1])
            g = math.degrees(math.atan2(abs(b[2] - a[2]), h))
            L += h
            rise += b[2] - a[2]
            worst = max(worst, g)
        ok = worst <= lim
        bad += not ok
        print(f"| {name} | {len(pts) - 1} | {L:.0f} m | {rise:+.0f} m | {worst:.1f}° | {lim}° | {'✓' if ok else '✗'} |")
    print()
    print("| 点 | 离最近的路 | 在草甸里 | 结果 |")
    print("|---|---|---|---|")
    for name, x, z in POINTS:
        d, which = min((seg_dist(x, z, a, b), r[0]) for r in ROUTES for a, b in zip(r[2], r[2][1:]))
        meadow = in_poly(x, z, MEADOW)
        ok = d <= 8 or meadow
        bad += not ok
        print(f"| {name} | {d:.1f} m（{which}） | {'是' if meadow else '否'} | {'✓' if ok else '✗'} |")
    print()
    print("全部通过" if not bad else f"{bad} 项不通过")


if __name__ == "__main__":
    main()
